// Spicy keeps the mild prompts in the pool too, so it never runs dry.
export function promptBank(category, intensity, kind) {
  const categories = category === 'mix' ? Object.values(PROMPTS) : [PROMPTS[category]];
  const levels = intensity === 'spicy' ? ['mild', 'spicy'] : ['mild'];
  return categories.flatMap((c) => levels.flatMap((level) => c[kind][level]));
}
